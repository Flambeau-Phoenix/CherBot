// Generates CherBot.Core type maps from the REA evidence:
//   - EventType ids, sources and display names (Streamer.bot.Common EventType enum)
//   - Sub-action type ids, names, categories and field lists (subaction-types.json)
//   - Trigger field lists per event type (trigger-types.json)
// Usage: dotnet run --project tools/GenTypeMaps -- <rea-root> <output-dir>
using System.Text;
using System.Text.Json;
using System.Text.RegularExpressions;

var reaRoot = args.Length > 0 ? args[0] : Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "..", ".."));
var outDir = args.Length > 1 ? args[1] : Path.GetFullPath(Path.Combine(AppContext.BaseDirectory, "..", "..", "..", "..", "..", "src", "CherBot.Core", "Generated"));

var eventTypePath = Path.Combine(reaRoot, "rea-full", "src", "Streamer.bot.Common", "Streamer.bot.Common.Events", "EventType.cs");
var eventSourcePath = Path.Combine(reaRoot, "rea-full", "src", "Streamer.bot.Common", "Streamer.bot.Common.Events", "EventSource.cs");
var subActionsPath = Path.Combine(reaRoot, "rea-work", "evidence", "schema", "subaction-types.json");
var triggersPath = Path.Combine(reaRoot, "rea-work", "evidence", "schema", "trigger-types.json");

foreach (var p in new[] { eventTypePath, eventSourcePath, subActionsPath, triggersPath })
    if (!File.Exists(p)) { Console.Error.WriteLine($"missing input: {p}"); return 1; }

Directory.CreateDirectory(outDir);

// ── event sources ──────────────────────────────────────────────────────────
var sourceRx = new Regex(@"\[\w+\(""(?<display>[^""]*)""\)\]\s*(?<name>\w+)\s*=\s*(?<id>[\w.]+)", RegexOptions.Multiline);
var sources = sourceRx.Matches(File.ReadAllText(eventSourcePath))
    .Select(m => (Name: m.Groups["name"].Value, Display: m.Groups["display"].Value))
    .Where(s => s.Name != "Invalid")
    .ToList();

// ── event types ────────────────────────────────────────────────────────────
var typeRx = new Regex(@"\[\w+\((?:EventSource\.(?<source>\w+),\s*)?""(?<display>[^""]*)""\)\]\s*(?<name>\w+)\s*=\s*(?<id>-?\d+)", RegexOptions.Multiline);
var triggerDoc = JsonDocument.Parse(File.ReadAllText(triggersPath));
var triggerInfo = new Dictionary<string, (string Category, string[] Fields)>();
foreach (var t in triggerDoc.RootElement.EnumerateArray())
{
    var name = t.GetProperty("event_type").GetString()!;
    var cats = string.Join(" / ", t.GetProperty("categories").EnumerateArray().Select(c => c.GetString()));
    var fields = t.GetProperty("fields").EnumerateArray().Select(f => $"{f.GetProperty("json").GetString()}:{f.GetProperty("type").GetString()}").ToArray();
    triggerInfo[name] = (cats, fields);
}

var events = new StringBuilder();
events.AppendLine("// <auto-generated> by tools/GenTypeMaps from REA evidence. Do not edit. </auto-generated>");
events.AppendLine("namespace CherBot.Core.Generated;");
events.AppendLine();
events.AppendLine("public static partial class EventTypes");
events.AppendLine("{");
events.AppendLine("    public static readonly string[] Sources =");
events.AppendLine("    [");
foreach (var s in sources) events.AppendLine($"        \"{s.Name}\",");
events.AppendLine("    ];");
events.AppendLine();
events.AppendLine("    public static readonly EventTypeInfo[] All =");
events.AppendLine("    [");
var typeCount = 0;
foreach (Match m in typeRx.Matches(File.ReadAllText(eventTypePath)))
{
    var name = m.Groups["name"].Value;
    var source = m.Groups["source"].Success ? m.Groups["source"].Value : "General";
    var type = name.StartsWith(source, StringComparison.Ordinal) && name.Length > source.Length ? name[source.Length..] : name;
    var (cat, fields) = triggerInfo.TryGetValue(name, out var ti) ? ti : ("", Array.Empty<string>());
    events.AppendLine($"        new({m.Groups["id"].Value}, \"{name}\", \"{source}\", \"{type}\", \"{Esc(m.Groups["display"].Value)}\", \"{Esc(cat)}\", [{string.Join(", ", fields.Select(f => $"\"{f}\""))}]),");
    typeCount++;
}
events.AppendLine("    ];");
events.AppendLine("}");
File.WriteAllText(Path.Combine(outDir, "EventTypes.g.cs"), events.ToString());

// The EventType enum itself, for scripts that call CPH.GetEventType() (Streamer.bot.Common.Events namespace).
var interfaceOut = Path.GetFullPath(Path.Combine(outDir, "..", "..", "CherBot.Plugin.Interface", "Generated"));
Directory.CreateDirectory(interfaceOut);
var enumSrc = new StringBuilder();
enumSrc.AppendLine("// <auto-generated> by tools/GenTypeMaps from REA evidence. Do not edit. </auto-generated>");
enumSrc.AppendLine("namespace Streamer.bot.Common.Events;");
enumSrc.AppendLine();
enumSrc.AppendLine("public enum EventType");
enumSrc.AppendLine("{");
enumSrc.AppendLine("    Unknown = 0,");
foreach (Match m in typeRx.Matches(File.ReadAllText(eventTypePath)))
    enumSrc.AppendLine($"    {m.Groups["name"].Value} = {m.Groups["id"].Value},");
enumSrc.AppendLine("}");
File.WriteAllText(Path.Combine(interfaceOut, "EventType.g.cs"), enumSrc.ToString());

// ── sub-action types ───────────────────────────────────────────────────────
var subDoc = JsonDocument.Parse(File.ReadAllText(subActionsPath));
var subs = new StringBuilder();
subs.AppendLine("// <auto-generated> by tools/GenTypeMaps from REA evidence. Do not edit. </auto-generated>");
subs.AppendLine("namespace CherBot.Core.Generated;");
subs.AppendLine();
subs.AppendLine("public static partial class SubActionTypes");
subs.AppendLine("{");
subs.AppendLine("    public static readonly SubActionTypeInfo[] All =");
subs.AppendLine("    [");
var subCount = 0;
foreach (var s in subDoc.RootElement.GetProperty("registered").EnumerateArray())
{
    var id = s.GetProperty("type_id").GetInt32();
    var name = s.GetProperty("type_name").GetString()!;
    var display = s.TryGetProperty("display", out var d) ? d.GetString() ?? "" : "";
    var cats = string.Join(" / ", s.GetProperty("categories").EnumerateArray().Select(c => c.GetString()));
    var fields = s.GetProperty("fields").EnumerateArray().Select(f => $"{f.GetProperty("json").GetString()}:{f.GetProperty("type").GetString()}");
    subs.AppendLine($"        new({id}, \"{name}\", \"{Esc(display)}\", \"{Esc(cats)}\", [{string.Join(", ", fields.Select(f => $"\"{Esc(f)}\""))}]),");
    subCount++;
}
subs.AppendLine("    ];");
subs.AppendLine("}");
File.WriteAllText(Path.Combine(outDir, "SubActionTypes.g.cs"), subs.ToString());

Console.WriteLine($"wrote {typeCount} event types, {sources.Count} sources, {subCount} sub-action types to {outDir}");
return 0;

static string Esc(string s) => s.Replace("\\", "\\\\").Replace("\"", "\\\"");
